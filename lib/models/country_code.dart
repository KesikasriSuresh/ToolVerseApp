class CountryCode {
  final String name;
  final String dialCode;
  final String code;
  final String flag;
  final String example;
  final int minDigits;
  final int maxDigits;

  const CountryCode({
    required this.name,
    required this.dialCode,
    required this.code,
    required this.flag,
    this.example = '98765 43210',
    this.minDigits = 7,
    this.maxDigits = 12,
  });

  @override
  bool operator ==(Object other) =>
      identical(this, other) ||
      other is CountryCode &&
          runtimeType == other.runtimeType &&
          dialCode == other.dialCode &&
          code == other.code;

  @override
  int get hashCode => dialCode.hashCode ^ code.hashCode;
}

